/// Shared plumbing: wrap a fixture in a rectangle header and run it through the
/// real dispatch path, so the encoding number and the decoder stay in agreement.
enum CompressedHarness {
    static func decode(
        _ fixture: [UInt8],
        encoding: RFB.Encoding,
        rect: Rect,
        into framebuffer: Framebuffer
    ) async throws {
        var payload = Data()
        payload.append(contentsOf: [UInt8(rect.x >> 8), UInt8(rect.x & 0xFF)])
        payload.append(contentsOf: [UInt8(rect.y >> 8), UInt8(rect.y & 0xFF)])
        payload.append(contentsOf: [UInt8(rect.width >> 8), UInt8(rect.width & 0xFF)])
        payload.append(contentsOf: [UInt8(rect.height >> 8), UInt8(rect.height & 0xFF)])
        let raw = UInt32(bitPattern: encoding.rawValue)
        payload.append(contentsOf: [
            UInt8(truncatingIfNeeded: raw >> 24), UInt8(truncatingIfNeeded: raw >> 16),
            UInt8(truncatingIfNeeded: raw >> 8), UInt8(truncatingIfNeeded: raw),
        ])
        payload.append(contentsOf: fixture)

        let decoder = RFBDecoder(
            stream: MemoryByteStream(inbound: payload),
            framebuffer: framebuffer,
            streams: try RFBStreams()
        )
        _ = try await decoder.decodeRectangle()
    }

    static func pixel(_ framebuffer: Framebuffer, _ x: Int, _ y: Int) -> [UInt8] {
        let (width, _, pixels) = framebuffer.snapshot()
        let base = (y * width + x) * 4
        return Array(pixels[base..<(base + 4)])
    }
}

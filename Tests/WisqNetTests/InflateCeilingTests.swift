    private func data(_ base64: String) throws -> Data {
        try XCTUnwrap(Data(base64Encoded: base64))
    }

    /// The probe has to say "something here" before any refusal below means
    /// anything: a fixture that did not expand would make them all pass for the
    /// wrong reason.
    func testTheBombReallyExpands() throws {
        let compressed = try data(Self.eightMebibytesOfZeros)
        XCTAssertLessThan(compressed.count, 64 * 1024, "la bombe ne comprime pas")

        let stream = try InflateStream()
        let out = try stream.inflate(compressed, limit: 8 * 1024 * 1024)
        XCTAssertEqual(out.count, 8 * 1024 * 1024)
        XCTAssertGreaterThan(
            out.count / max(1, compressed.count), 100,
            "rapport trop faible pour que la démonstration tienne")
    }

    /// The defect. Without a ceiling this allocates eight mebibytes from a few
    /// kibibytes; with one the bytes are never there.
    func testAStreamBeyondItsCeilingIsRefused() throws {
        let compressed = try data(Self.eightMebibytesOfZeros)
        let stream = try InflateStream()
        XCTAssertThrowsError(try stream.inflate(compressed, limit: 64 * 1024)) { error in
            guard case WisqError.malformedMessage(let message) = error else {
                return XCTFail("erreur inattendue : \(error)")
            }
            XCTAssertTrue(message.contains("plafond"), "le refus doit nommer le plafond : \(message)")
        }
    }

    /// The other edge, and half the work: what stays within its ceiling comes
    /// back whole. A ceiling that refused everything would pass the test above
    /// and break every real server.
    func testAStreamWithinItsCeilingComesBackWhole() throws {
        let stream = try InflateStream()
        let out = try stream.inflate(try data(Self.twoHundredKibibytesOfA), limit: 200 * 1024)
        XCTAssertEqual(out.count, 200 * 1024)
        XCTAssertTrue(out.allSatisfy { $0 == UInt8(ascii: "A") })
    }

    /// Exactly at the ceiling is within it — and that is the commonest case
    /// there is, since every caller passes the size it demands back.
    func testExactlyTheCeilingIsAccepted() throws {
        let stream = try InflateStream()
        XCTAssertEqual(
            try stream.inflate(try data(Self.oneHundredThousandB), limit: 100_000).count, 100_000)
    }

    /// One byte under it is not.
    func testOneByteOverTheCeilingIsRefused() throws {
        let stream = try InflateStream()
        XCTAssertThrowsError(try stream.inflate(try data(Self.oneHundredThousandB), limit: 99_999))
    }

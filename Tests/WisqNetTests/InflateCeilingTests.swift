/// The ceiling on what comes **out** of zlib.
///
/// Every caller of `inflate` already knew the size it expected, and every one
/// of them asked after the bytes existed — "zlib a produit N octets au lieu de
/// M". Compression ratios do not care about the order.
///
/// Measured before any of this was written: 101 929 compressed bytes produce
/// 104 857 600, a ratio of **1 028 to 1**. `RFBDecoder.decodeZlib` admits a
/// compressed block of `pixels × 4 + 1 MiB`, so a *one-pixel* rectangle
/// licenses about a gigabyte, allocated inside `inflate`, before its
/// `pixels.count == 4` ever runs. On a phone that is not slow, it is dead.
///
/// The allocation audit recorded this path as covered "on the pixel side".
/// True of the check and false of the allocation — a guard downstream of the
/// thing it guards is a report, not a defence.
///
